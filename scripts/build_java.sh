#!/usr/bin/env bash
# Compiles the hand-written Java helpers in java/ to smali and drops them into android_project/smali.
#   javac (-source/-target 8, bootclasspath = Android 2.1 / API 7 android.jar)  -> catches any API 8+ use
#   dx 30.0.2 (via dex2jar's d2j-jar2dex, DEX 035)  ->  baksmali (bundled in tools/apktool.jar, tools/src/Dex2Smali.java)
# Run this after editing anything in java/, then ./scripts/build_apk.sh.
# The hand-written smali (R, SettingsActivity, ImageUtil, ...) is assembled and converted to a jar first, so the Java code can
# use it (javac -classpath); R.* ids are compile-time constants and get inlined.
# Classes generated from java/ (do not hand-edit their smali):
#   listed in java/GENERATED_SMALI.txt (rewritten on every run; stale files from the previous run are deleted)
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
C="$ROOT/tools/.java-toolchain"; mkdir -p "$C"
if [ ! -d "$C/dex-tools" ]; then
    curl -fsSL -o "$C/d2j.zip" https://github.com/pxb1988/dex2jar/releases/download/v2.4/dex-tools-v2.4.zip
    unzip -q -o "$C/d2j.zip" -d "$C" && mv "$C/dex-tools-v2.4" "$C/dex-tools" && rm "$C/d2j.zip"
    chmod +x "$C"/dex-tools/*.sh
fi
[ -s "$C/android-7.jar" ] || curl -fsSL -o "$C/android-7.jar" https://raw.githubusercontent.com/Sable/android-platforms/master/android-7/android.jar

W="$C/work"; rm -rf "$W"; mkdir -p "$W/classes"
LIST="$ROOT/java/GENERATED_SMALI.txt"
# classpath: hand-written smali only (generated files from the previous run are left out; java/ is their source)
if [ ! -s "$C/d2s/Smali2Dex.class" ] || [ "$ROOT/tools/src/Smali2Dex.java" -nt "$C/d2s/Smali2Dex.class" ]; then
    mkdir -p "$C/d2s"; javac -nowarn -cp "$ROOT/tools/apktool.jar" -d "$C/d2s" "$ROOT/tools/src/Smali2Dex.java" "$ROOT/tools/src/Dex2Smali.java"
fi
cp -r "$ROOT/android_project/smali" "$W/cpsmali"
if [ -f "$LIST" ]; then while read -r f; do [ -n "$f" ] && rm -f "$W/cpsmali/$f"; done < "$LIST"; fi
java -cp "$C/d2s:$ROOT/tools/apktool.jar" Smali2Dex "$W/cpsmali" "$W/cp.dex" 2>&1 | grep -v "JAVA_TOOL_OPTIONS" || true
"$C/dex-tools/d2j-dex2jar.sh" -f -o "$W/cp.jar" "$W/cp.dex" >/dev/null 2>&1
[ -s "$W/cp.jar" ] || { echo "could not build the smali classpath"; exit 1; }
javac -nowarn -source 8 -target 8 -encoding UTF-8 -bootclasspath "$C/android-7.jar" -classpath "$W/cp.jar" \
      -d "$W/classes" $(find "$ROOT/java" -name "*.java") 2>&1 | grep -v "^warning: \[options\]\|^[0-9]* warning" || true
[ -n "$(find "$W/classes" -name '*.class')" ] || { echo "javac failed"; exit 1; }
(cd "$W/classes" && jar cf "$W/helpers.jar" .)
"$C/dex-tools/d2j-jar2dex.sh" -f -o "$W/helpers.dex" "$W/helpers.jar" >/dev/null 2>&1
# baksmali from apktool.jar (same smali dialect as the assembler used by build_apk.sh)
java -cp "$C/d2s:$ROOT/tools/apktool.jar" Dex2Smali "$W/helpers.dex" "$W/smali"
# remove smali generated by the previous run (classes deleted or renamed in java/ must not linger)
if [ -f "$LIST" ]; then
    while read -r f; do [ -n "$f" ] && rm -f "$ROOT/android_project/smali/$f"; done < "$LIST"
fi
: > "$LIST"
n=0
for f in $(cd "$W/smali" && find . -name "*.smali" | sed 's#^\./##' | sort); do
    echo "$f" >> "$LIST"
    mkdir -p "$ROOT/android_project/smali/$(dirname "$f")"
    cp "$W/smali/$f" "$ROOT/android_project/smali/$f"; n=$((n+1))
done
echo "build_java: $n smali files updated from java/"
